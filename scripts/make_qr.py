# /// script
# requires-python = ">=3.10"
# dependencies = ["segno>=1.6"]
# ///
"""Generate one QR code (PNG + SVG) per ref source for the intake form.

Usage:
    uv run scripts/make_qr.py --base-url https://chiranr19.github.io/bullseye-intake/
    uv run scripts/make_qr.py --base-url ... --dry-run
    uv run scripts/make_qr.py --base-url ... --out qr --size 1200 --sources flyer truck

Each code encodes <base-url>?ref=<source>. Output goes to qr/<source>.png and qr/<source>.svg,
plus qr/README.md listing the exact URL inside each code. Existing files are replaced.
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

import segno

log = logging.getLogger("make_qr")

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_JS = REPO_ROOT / "config.js"

# Keep in step with REF_SOURCES in config.js (the script warns if they drift).
DEFAULT_SOURCES = ("flyer", "truck", "text", "web", "russell")
ERROR_LEVEL = "q"  # ~25% of the symbol can be damaged and still scan; fine for a scuffed truck magnet
QUIET_ZONE_MODULES = 4

PURPOSE = {
    "flyer": "Print on the paper flyer",
    "truck": "Magnet or decal on the truck",
    "text": "Not for print: this is the link Russell texts to customers",
    "web": "For a website or online listing",
    "russell": "Russell's own phone: open this link and hand the phone over at the car",
}


@dataclass(frozen=True)
class Job:
    source: str
    url: str
    png: Path
    svg: Path


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-url", required=True, help="Live page URL, e.g. https://user.github.io/bullseye-intake/")
    p.add_argument("--out", default=str(REPO_ROOT / "qr"), help="Output folder (default: qr/)")
    p.add_argument("--size", type=int, default=1200, help="Target PNG width in pixels (default: 1200)")
    p.add_argument("--sources", nargs="+", default=list(DEFAULT_SOURCES), help="Ref sources to generate")
    p.add_argument("--dry-run", action="store_true", help="Show what would be written; write nothing")
    return p.parse_args(argv)


def normalize_base_url(raw: str) -> str:
    """Accept only a clean https page URL; return it with a trailing slash and no query."""
    parts = urlsplit(raw.strip())
    if parts.scheme != "https":
        raise ValueError(f"base URL must start with https:// (got {raw!r})")
    if not parts.netloc:
        raise ValueError(f"base URL has no host (got {raw!r})")
    if parts.query or parts.fragment:
        raise ValueError("base URL must not contain ?query or #fragment; the script adds ?ref= itself")
    path = parts.path or "/"
    if not path.endswith("/"):
        path += "/"
    return f"https://{parts.netloc}{path}"


def check_sources(sources: list[str]) -> list[str]:
    cleaned: list[str] = []
    for s in sources:
        s = s.strip().lower()
        if not re.fullmatch(r"[a-z]{1,20}", s):
            raise ValueError(f"source {s!r} must be 1-20 lowercase letters")
        if s not in cleaned:
            cleaned.append(s)
    if not cleaned:
        raise ValueError("no sources given")
    return cleaned


def config_sources() -> list[str] | None:
    """REF_SOURCES from config.js, or None if the file cannot be read or parsed."""
    try:
        text = CONFIG_JS.read_text(encoding="utf-8")
    except OSError:
        return None
    m = re.search(r"REF_SOURCES\s*:\s*\[([^\]]*)\]", text)
    if not m:
        return None
    return re.findall(r'"([a-z]+)"', m.group(1))


def build_jobs(base_url: str, sources: list[str], out: Path) -> list[Job]:
    return [Job(s, f"{base_url}?ref={s}", out / f"{s}.png", out / f"{s}.svg") for s in sources]


def write_code(job: Job, size: int) -> int:
    """Write PNG and SVG for one job. Returns the PNG scale used (pixels per module)."""
    qr = segno.make(job.url, error=ERROR_LEVEL)
    modules, _ = qr.symbol_size(scale=1, border=QUIET_ZONE_MODULES)
    scale = max(1, size // modules)
    qr.save(str(job.png), kind="png", scale=scale, border=QUIET_ZONE_MODULES, dark="#000000", light="#ffffff")
    qr.save(str(job.svg), kind="svg", scale=10, border=QUIET_ZONE_MODULES, dark="#000000", light="#ffffff",
            xmldecl=True, svgclass=None, lineclass=None)
    return scale


def readme_text(jobs: list[Job], size: int) -> str:
    lines = [
        "# QR codes",
        "",
        "Generated by `scripts/make_qr.py`. Do not edit by hand; re-run the script if the URL changes.",
        "",
        f"PNG is about {size}px wide (print at 2 inches or larger). SVG scales to any size.",
        f"Error correction level {ERROR_LEVEL.upper()}, {QUIET_ZONE_MODULES}-module quiet zone.",
        "",
        "| File | Use | Encodes |",
        "|---|---|---|",
    ]
    for j in jobs:
        lines.append(f"| `{j.png.name}` / `{j.svg.name}` | {PURPOSE.get(j.source, '')} | `{j.url}` |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)
    args = parse_args(argv)
    try:
        base_url = normalize_base_url(args.base_url)
        sources = check_sources(args.sources)
    except ValueError as e:
        log.error("error: %s", e)
        return 2

    known = config_sources()
    if known is not None:
        extra = sorted(set(sources) - set(known))
        if extra:
            log.warning("warning: %s not in config.js REF_SOURCES; the page will record those scans as 'direct'",
                        ", ".join(extra))

    out = Path(args.out)
    jobs = build_jobs(base_url, sources, out)
    if args.dry_run:
        log.info("dry run: would write to %s", out)
        for j in jobs:
            log.info("  %-10s %s  ->  %s, %s", j.source, j.url, j.png.name, j.svg.name)
        log.info("  README.md")
        return 0

    out.mkdir(parents=True, exist_ok=True)
    for j in jobs:
        scale = write_code(j, args.size)
        log.info("wrote %s and %s  (%s, %dpx/module)", j.png.name, j.svg.name, j.url, scale)
    (out / "README.md").write_text(readme_text(jobs, args.size), encoding="utf-8")
    log.info("wrote README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
